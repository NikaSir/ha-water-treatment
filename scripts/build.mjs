// Identity is tied to the actual shipped bytes, not the checked-out revision.
const packageRoot = resolve(projectRoot, "custom_components/water_treatment");
async function packageFiles(dir = "") {
  const entries = await readdir(resolve(packageRoot, dir), {withFileTypes: true});
  const result = [];
  for (const entry of entries) {
    if (entry.name === "__pycache__" || entry.name === "notification_build.json" || entry.name === "_notification_build.py" || entry.name.endsWith(".pyc")) continue;
    const path = dir ? `${dir}/${entry.name}` : entry.name;
    if (entry.isDirectory()) result.push(...await packageFiles(path));
    else if (entry.isFile()) result.push(path);
    else throw new Error(`Unexpected package entry: ${path}`);
  }
  return result.sort();
}
const sha = bytes => createHash("sha256").update(bytes).digest("hex");
const files = Object.fromEntries(await Promise.all((await packageFiles()).map(async path => [path, sha(await readFile(resolve(packageRoot, path)))])));
const fingerprint = sha(JSON.stringify(files));
const version = JSON.parse(await readFile(resolve(packageRoot, "manifest.json"), "utf8")).version;
const manifest = JSON.stringify({schema_version: 1, version, fingerprint, files}, null, 2) + "\n";
const python = `"""Generated at build time; do not edit."""
import hashlib
import json
from pathlib import Path

FINGERPRINT = ${JSON.stringify(fingerprint)}
VERSION = ${JSON.stringify(version)}
FILES = ${JSON.stringify(files, null, 2)}

def verify_package(root):
    """Check imported identity against the installed package; run in executor."""
    root = Path(root)
    try:
        manifest = json.loads((root / 'notification_build.json').read_text(encoding='utf-8'))
        if manifest != {'schema_version': 1, 'version': VERSION, 'fingerprint': FINGERPRINT, 'files': FILES}:
            return False
        actual = {path.relative_to(root).as_posix() for path in root.rglob('*')
                  if path.is_file() and '__pycache__' not in path.parts
                  and not path.name.endswith('.pyc')
                  and path.name not in ('notification_build.json', '_notification_build.py')}
        return actual == set(FILES) and all(
            hashlib.sha256((root / name).read_bytes()).hexdigest() == digest
            for name, digest in FILES.items())
    except (OSError, ValueError, TypeError):
        return False
`;
for (const [name, content] of [["notification_build.json", manifest], ["_notification_build.py", python]]) {
  const path = resolve(packageRoot, name);
  if (process.argv.includes("--check")) {
    if (await readFile(path, "utf8").catch(() => "") !== content) throw new Error(`${name} is not synchronized; run npm run build`);
  } else await writeFile(path, content, "utf8");
}
