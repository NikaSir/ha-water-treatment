import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const frontendRoot = resolve(projectRoot, "custom_components/water_treatment/frontend");
const sourceRoot = resolve(frontendRoot, "src");
const target = resolve(frontendRoot, "water-treatment-panel.js");
const shellPath = "templates/shell_v2/nikas-specialized-shell.js";

const [shellSource, zoomSource, coreSource, cssSource, treatmentSource, overviewModel, overviewUi] = await Promise.all([
  readFile(resolve(projectRoot, shellPath), "utf8"),
  readFile(resolve(sourceRoot, "zoom-controller.js"), "utf8"),
  readFile(resolve(sourceRoot, "water-treatment-panel-core.js"), "utf8"),
  readFile(resolve(sourceRoot, "styles.css"), "utf8"),
  readFile(resolve(sourceRoot, "treatment-ui.js"), "utf8"),
  readFile(resolve(sourceRoot, "overview-model.js"), "utf8"),
  readFile(resolve(sourceRoot, "overview-ui.js"), "utf8"),
]);

const marker = 'const TREATMENT_CSS = "__WATER_TREATMENT_CSS__";';
if (!coreSource.includes(marker)) {
  throw new Error("CSS marker is missing from the frontend core");
}

const hydratedCore = coreSource.replace(
  marker,
  `// BEGIN custom_components/water_treatment/frontend/src/styles.css\nconst TREATMENT_CSS = ${JSON.stringify(cssSource.trim() + "\n")};\n// END custom_components/water_treatment/frontend/src/styles.css`,
);
const banner = "/* NikaS Water Treatment UI v0.2.0-beta001 · generated by scripts/build.mjs */\n";
const bundle = banner
  + `// BEGIN ${shellPath}\n${shellSource.trim()}\n// END ${shellPath}\n\n`
  + `// BEGIN custom_components/water_treatment/frontend/src/zoom-controller.js\n${zoomSource.trim()}\n// END custom_components/water_treatment/frontend/src/zoom-controller.js\n\n`
  + `// BEGIN custom_components/water_treatment/frontend/src/treatment-ui.js\n${treatmentSource.trim()}\n// END custom_components/water_treatment/frontend/src/treatment-ui.js\n\n`
  + `// BEGIN custom_components/water_treatment/frontend/src/overview-model.js\n${overviewModel.trim()}\n// END custom_components/water_treatment/frontend/src/overview-model.js\n\n`
  + `// BEGIN custom_components/water_treatment/frontend/src/overview-ui.js\n${overviewUi.trim()}\n// END custom_components/water_treatment/frontend/src/overview-ui.js\n\n`
  + `// BEGIN custom_components/water_treatment/frontend/src/water-treatment-panel-core.js\n${hydratedCore.trim()}\n// END custom_components/water_treatment/frontend/src/water-treatment-panel-core.js\n`;

if (process.argv.includes("--check")) {
  const current = await readFile(target, "utf8").catch(() => "");
  if (current !== bundle) {
    throw new Error("Production bundle is not synchronized; run node scripts/build.mjs");
  }
  process.stdout.write(`Bundle is synchronized: ${target}\n`);
} else {
  await writeFile(target, bundle, "utf8");
  process.stdout.write(`Built ${target}\n`);
}
